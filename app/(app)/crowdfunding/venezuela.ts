// The country's outline, and the one projection both it and the pins use.
//
// The shape is real data — Natural Earth 50m (public domain), simplified with
// Douglas-Peucker at 0.015 degrees (~1.6 km) down to 357 points across five
// rings: the mainland plus the islands worth drawing. Drawing a country by
// hand produces something that *looks* like the country until it is put next
// to one, and this map's whole job is to be believed.
//
// `project()` is shared on purpose. If the outline and the pins agreed about
// the world through two different formulas, a business in Yaracuy would sit in
// the sea — a wrong pin is worse than no map, because it looks like a fact.

/** Bounding box of the outline: [lngMin, latMin, lngMax, latMax]. */
export const BBOX: [number, number, number, number] = [-73.3662, 0.6880, -59.8316, 12.1779];

/**
 * The drawing surface, in the same units the projection writes.
 *
 * Equirectangular with no correction: Venezuela sits within six degrees of the
 * equator, where cos(lat) is 0.99 — a distortion below one percent, far
 * smaller than the simplification of the coastline itself.
 */
