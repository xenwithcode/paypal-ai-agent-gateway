/** Degrees to SVG units, once, for the country and for every pin. */
export function project(lng: number, lat: number): { x: number; y: number } {
  return {
    x: ((lng - BBOX[0]) / (BBOX[2] - BBOX[0])) * MAP_WIDTH,
    y: ((BBOX[3] - lat) / (BBOX[3] - BBOX[1])) * MAP_HEIGHT,
  };
}

/** The country as a single path, built once at module load. */
export const OUTLINE_PATH: string = OUTLINE.map(
  (ring) =>
    "M" +
    ring
      .map(([lng, lat]) => {
        const { x, y } = project(lng, lat);
        return `${x.toFixed(1)},${y.toFixed(1)}`;
      })
      .join("L") +
    "Z"
).join(" ");
